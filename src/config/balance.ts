/**
 * 【持久力を上げた手ごたえ】持久力（stats.stamina）は、
 * 体力の**総量**・練習の**消費**・コマ間の**回復**の3つすべてに効く。
 *
 *   持久力10 … 体力57 ／ 消費 ×1.17 ／ コマ間の回復 6
 *   持久力40 … 体力86 ／ 消費 ×0.91 ／ コマ間の回復 11
 *   持久力80 … 体力124 ／ 消費 ×0.57 ／ コマ間の回復 18
 *
 * 実測（育成B・3コマを回した日の終わりに残っている体力）
 *   持久力 5 → 17%（もう限界）／ 40 → 34%／ 80 → 83%／ 95 → 98%（ほとんど減らない）
 * 「持久力を鍛えれば練習をたくさん積める」が数字で見えるようにしてある。
 *
 * ここを触ると育成以上の練習量がまるごと変わるので、
 * **必ず growthcheck.ts で1日の伸びを測り直すこと。**
 */
