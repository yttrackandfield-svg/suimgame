import Phaser from "phaser";

/**
 * 作ったばかりのボタンを「その場で」押せるようにする。
 *
 * 【なぜ必要か】
 * Phaser は setInteractive したオブジェクトをいったん待ち行列に入れておき、
 * **次のフレームの先頭**で当たり判定の一覧へ移す。
 * いっぽうタッチは DOM のイベントから直接その場で処理される（フレームを待たない）。
 * つまり「画面を開いた直後の指」は、まだ一覧に居ないボタンを探しにいって
 * どこにも当たらず、そのタップは無かったことになる。
 *
 * ふつうは1フレーム（16ms）の話なので気づかない。
 * ところがこのゲームは画面を開くときに文字を大量に作るので、
 * その1フレームがスマホでは数百ミリ秒かかることがある。
 * その間タップがすべて捨てられ、「画面が変わったあと、少し間を置かないと押せない」
 * という状態になる。
 *
 * ここでは待ち行列をすぐ流し込んで、作った直後から押せる状態にする。
 * **画面（モーダル・オーバーレイ）を組み立て終わったら呼ぶこと。**
 *
 * preUpdate は Phaser の内部向けで型定義に出ていないため、必要な形だけ書いて呼ぶ。
 */
interface PendingInput {
  preUpdate?: () => void;
}

export function flushInput(scene: Phaser.Scene): void {
  (scene.input as unknown as PendingInput).preUpdate?.();
}
